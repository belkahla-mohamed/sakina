export function formatPrice(value: number, lang: Lang): string {
  const formatted = value
    .toFixed(2)
    .replace(".", ",")
    .replace(/\B(?=(\d{3})+(?!\d))/g, " ");
  return lang === "ar" ? `${formatted} درهم` : `${formatted} dh`;
}
