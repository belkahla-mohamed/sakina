export type TKey = keyof typeof dict.fr;
export type Lang = "fr" | "ar";

export function translate(lang: Lang, key: TKey): string {
  return dict[lang][key] ?? dict.fr[key];
}

export function formatPrice(value: number, lang: Lang): string {
  const formatted = value
    .toFixed(2)
    .replace(".", ",")
    .replace(/\B(?=(\d{3})+(?!\d))/g, " ");
  return lang === "ar" ? `${formatted} درهم` : `${formatted} dh`;
}
